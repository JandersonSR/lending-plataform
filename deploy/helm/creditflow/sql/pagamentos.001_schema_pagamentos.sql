-- Schema do módulo Pagamentos: DDL de referência.
-- É o que a migração do EF Core (PagamentosDbContext) deve gerar; serve para revisar a migração
-- e para rodar à mão num Postgres local (validado em PostgreSQL 16).
-- Convenção: nomes em snake_case declarados explicitamente no mapeamento do EF.

CREATE SCHEMA IF NOT EXISTS pagamentos;

-- ---------------------------------------------------------------------------
-- Agregado Desembolso: um por proposta (a saga nunca desembolsa duas vezes a mesma proposta)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pagamentos.desembolsos (
    id                   uuid        PRIMARY KEY,
    proposta_id          uuid        NOT NULL,
    cliente_id           uuid        NOT NULL,
    valor_centavos       bigint      NOT NULL CHECK (valor_centavos > 0),
    chave_pix            text        NOT NULL,
    usuario_id           text        NULL,         -- sub do Keycloak: o cliente só vê o que é dele
    status               text        NOT NULL,
    tentativas           integer     NOT NULL DEFAULT 0,
    id_transacao_gateway text        NULL,
    motivo_falha         text        NULL,
    detalhe_falha        text        NULL,
    solicitado_em        timestamptz NOT NULL,
    concluido_em         timestamptz NULL,
    versao               integer     NOT NULL DEFAULT 0,          -- concorrência otimista
    CONSTRAINT uq_desembolsos_proposta UNIQUE (proposta_id)
);

-- ---------------------------------------------------------------------------
-- Agregado Parcela: criado quando o desembolso conclui (o cronograma veio no ContratoAssinado)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pagamentos.parcelas (
    id                uuid        PRIMARY KEY,
    desembolso_id     uuid        NOT NULL REFERENCES pagamentos.desembolsos (id),
    proposta_id       uuid        NOT NULL,
    cliente_id        uuid        NOT NULL,
    usuario_id        text        NULL,
    numero            integer     NOT NULL CHECK (numero > 0),
    valor_centavos    bigint      NOT NULL CHECK (valor_centavos > 0),
    vencimento        date        NOT NULL,
    status            text        NOT NULL,
    valor_pago_centavos bigint    NULL,
    paga_em           timestamptz NULL,
    versao            integer     NOT NULL DEFAULT 0,
    CONSTRAINT uq_parcelas_proposta_numero UNIQUE (proposta_id, numero)
);
CREATE INDEX IF NOT EXISTS ix_parcelas_proposta ON pagamentos.parcelas (proposta_id);

-- ---------------------------------------------------------------------------
-- Idempotência dos comandos HTTP (Idempotency-Key): a mesma chave devolve a mesma resposta
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pagamentos.requisicoes_idempotentes (
    chave          text        PRIMARY KEY,
    hash_corpo     text        NOT NULL,       -- mesma chave com corpo diferente = 422
    status_http    integer     NOT NULL,
    resposta       jsonb       NOT NULL,
    criada_em      timestamptz NOT NULL
);

-- ---------------------------------------------------------------------------
-- O "banco do PSP" do gateway PIX simulado: a idempotência do lado de lá
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pagamentos.pix_simulado (
    chave_idempotencia text        PRIMARY KEY,
    situacao           text        NOT NULL,       -- processada | cancelada (lápide gravada pela consulta)
    id_transacao       text        NULL,
    chave_pix          text        NOT NULL,
    valor_centavos     bigint      NOT NULL,
    criada_em          timestamptz NOT NULL
);

-- ---------------------------------------------------------------------------
-- Outbox, faixas e inbox: as mesmas tabelas em todo schema que publica/consome
-- (mapeadas por ModelBuilder.AplicarMensageria("pagamentos") no BuildingBlocks)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pagamentos.outbox (
    id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id     uuid        NOT NULL,
    tipo          text        NOT NULL,
    versao        integer     NOT NULL,
    topico        text        NOT NULL,
    chave         text        NOT NULL,
    faixa         smallint    NOT NULL,
    conteudo      jsonb       NOT NULL,
    cabecalhos    jsonb       NOT NULL,
    ocorrido_em   timestamptz NOT NULL,
    criada_em     timestamptz NOT NULL,
    publicada_em  timestamptz NULL,
    tentativas    integer     NOT NULL DEFAULT 0,
    ultimo_erro   text        NULL,
    CONSTRAINT uq_outbox_evento UNIQUE (evento_id)
);
-- O relay só lê pendentes: índice parcial pequeno, que não cresce com o histórico publicado
CREATE INDEX IF NOT EXISTS ix_outbox_pendentes ON pagamentos.outbox (faixa, id) WHERE publicada_em IS NULL;
-- A limpeza apaga publicadas antigas
CREATE INDEX IF NOT EXISTS ix_outbox_publicada_em ON pagamentos.outbox (publicada_em) WHERE publicada_em IS NOT NULL;

CREATE TABLE IF NOT EXISTS pagamentos.outbox_faixas (
    faixa smallint PRIMARY KEY
);
INSERT INTO pagamentos.outbox_faixas (faixa)
SELECT g FROM generate_series(0, 15) AS g
ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS pagamentos.inbox (
    consumidor    text        NOT NULL,
    evento_id     uuid        NOT NULL,
    tipo          text        NOT NULL,
    processada_em timestamptz NOT NULL,
    PRIMARY KEY (consumidor, evento_id)
);
CREATE INDEX IF NOT EXISTS ix_inbox_processada_em ON pagamentos.inbox (processada_em);
